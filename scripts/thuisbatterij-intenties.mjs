const seenFiles = new Set();
const seenSlugs = new Set();
const seenSectionIds = new Set();
for (const page of batteryIntentPages) {
  for (const field of ['slug', 'file', 'phrase', 'linkLabel', 'title', 'h1', 'metaDescription', 'hero', 'serviceType', 'clusterLead']) {
    if (typeof page[field] !== 'string' || !page[field].trim()) throw new Error(`${page.file ?? 'Thuisbatterij-intentie'}: ${field} moet gevulde tekst bevatten.`);
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(page.slug)) throw new Error(`${page.file}: ongeldige slug ${page.slug}.`);
  if (page.file !== `${page.slug}.html`) throw new Error(`${page.file}: bestandsnaam en slug verschillen.`);
  if (page.metaDescription.length > 165) throw new Error(`${page.file}: metaDescription is langer dan 165 tekens.`);
  const phrase = page.phrase.toLocaleLowerCase('nl-NL');
  for (const field of ['title', 'h1', 'metaDescription', 'hero']) {
    if (!page[field].toLocaleLowerCase('nl-NL').includes(phrase)) throw new Error(`${page.file}: ${field} mist de zoekterm “${page.phrase}”.`);
  }
  const { intentSection } = page;
  if (!intentSection || typeof intentSection !== 'object') throw new Error(`${page.file}: intentSection ontbreekt.`);
  for (const field of ['id', 'heading', 'intro']) {
    if (typeof intentSection[field] !== 'string' || !intentSection[field].trim()) throw new Error(`${page.file}: intentSection.${field} moet gevulde tekst bevatten.`);
  }
  if (intentSection.closingHtml !== undefined && (typeof intentSection.closingHtml !== 'string' || !intentSection.closingHtml.trim())) {
    throw new Error(`${page.file}: intentSection.closingHtml moet bij gebruik gevulde tekst bevatten.`);
  }
  if (!Array.isArray(intentSection.cards) || intentSection.cards.length !== 4) throw new Error(`${page.file}: intentSection.cards moet exact vier kaarten bevatten.`);
  for (const [index, card] of intentSection.cards.entries()) {
    if (typeof card?.heading !== 'string' || !card.heading.trim() || typeof card?.text !== 'string' || !card.text.trim()) {
      throw new Error(`${page.file}: intentSection.cards[${index}] is onvolledig.`);
    }
  }
  if (!page.replacements || typeof page.replacements !== 'object' || Array.isArray(page.replacements) || !Object.keys(page.replacements).length) {
    throw new Error(`${page.file}: replacements moet gevulde vervangingen bevatten.`);
  }
  for (const [id, value] of Object.entries(page.replacements)) {
    if (!id || typeof value !== 'string' || !value.trim()) throw new Error(`${page.file}: ongeldige vervanging voor #${id}.`);
  }
  if (seenFiles.has(page.file) || seenSlugs.has(page.slug) || seenSectionIds.has(intentSection.id)) throw new Error(`${page.file}: dubbele intentieconfiguratie.`);
  seenFiles.add(page.file);
  seenSlugs.add(page.slug);
  seenSectionIds.add(intentSection.id);
}

export const batteryIntentPageFiles = batteryIntentPages.map(({ file }) => file);
